#!/usr/bin/env python3
"""
Converts the original LOVE game assets into formats the Vita port loads
without extra libraries (no SDL_image / SDL_ttf / SDL_mixer needed).

  usage: python3 tools/convert_assets.py <extracted_love_game_dir> <port_dir>

Needs: Pillow, ffmpeg.
Output: assets/*.rgba   (le32 w, le32 h, then w*h*4 RGBA bytes)
        assets/horror.pcm, assets/rain.pcm (mono, 22050 Hz, signed 16-bit LE)
        assets/font.rgba + src/font_data.h  (bitmap font atlas of Pixel.ttf @12)
        sce_sys/icon0.png (128x128 LiveArea icon)
"""
import os, struct, subprocess, sys
from PIL import Image, ImageDraw, ImageFont

src, dst = sys.argv[1], sys.argv[2]
A = os.path.join(dst, "assets")
os.makedirs(A, exist_ok=True)
os.makedirs(os.path.join(dst, "sce_sys"), exist_ok=True)

def to_rgba(path, name):
    im = Image.open(path).convert("RGBA")
    with open(os.path.join(A, name + ".rgba"), "wb") as f:
        f.write(struct.pack("<II", *im.size))
        f.write(im.tobytes())
    print("image", name, im.size)

for rel, name in [
    ("assets/banner.png", "banner"), ("assets/title.png", "title"),
    ("assets/light.png", "light"), ("assets/raintex.png", "raintex"),
    ("assets/player/default1.png", "player1"), ("assets/player/default2.png", "player2"),
    ("assets/player/gmonster1.png", "gmonster1"), ("assets/player/gmonster2.png", "gmonster2"),
    ("assets/player/rmonster1.png", "rmonster1"), ("assets/player/rmonster2.png", "rmonster2"),
]:
    to_rgba(os.path.join(src, rel), name)

# --- audio: mono 22.05 kHz s16le ---
for rel, name in [("audio/horror.mp3", "horror"), ("audio/thunderstorm.mp3", "rain")]:
    out = os.path.join(A, name + ".pcm")
    subprocess.check_call(["ffmpeg", "-y", "-v", "error", "-i", os.path.join(src, rel),
                           "-ac", "1", "-ar", "22050", "-f", "s16le", out])
    print("audio", name, os.path.getsize(out), "bytes")

# --- bitmap font atlas: ASCII 32..126, 16 columns, 32x32 cells ---
CELL, COLS = 32, 16
font = ImageFont.truetype(os.path.join(src, "assets/Pixel.ttf"), 12)
asc, desc = font.getmetrics()
chars = [chr(c) for c in range(32, 127)]
rows = (len(chars) + COLS - 1) // COLS
atlas = Image.new("L", (COLS * CELL, rows * CELL), 0)
adv = []
for i, ch in enumerate(chars):
    cell = Image.new("L", (CELL, CELL), 0)
    ImageDraw.Draw(cell).text((2, 0), ch, font=font, fill=255)
    bb = cell.getbbox()
    assert bb is None or (bb[2] < CELL and bb[3] < CELL), (ch, bb)
    atlas.paste(cell, ((i % COLS) * CELL, (i // COLS) * CELL))
    adv.append(int(round(font.getlength(ch))))
rgba = Image.merge("RGBA", [Image.new("L", atlas.size, 255)] * 3 + [atlas])
with open(os.path.join(A, "font.rgba"), "wb") as f:
    f.write(struct.pack("<II", *rgba.size)); f.write(rgba.tobytes())
with open(os.path.join(dst, "src", "font_data.h"), "w") as f:
    f.write("/* generated by tools/convert_assets.py */\n#pragma once\n")
    f.write("#define FONT_CELL %d\n#define FONT_COLS %d\n#define FONT_PAD_X 2\n" % (CELL, COLS))
    f.write("#define FONT_LINE_H %d\n" % (asc + desc))
    f.write("static const unsigned char font_adv[95] = {%s};\n" % ",".join(map(str, adv)))
print("font ok, line height", asc + desc)

# --- LiveArea icon ---
Image.open(os.path.join(src, "assets/icon.png")).convert("RGBA").resize((128, 128), Image.LANCZOS)\
     .save(os.path.join(dst, "sce_sys", "icon0.png"))
